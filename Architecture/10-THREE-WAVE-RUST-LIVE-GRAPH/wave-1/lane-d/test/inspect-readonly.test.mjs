import {test} from 'node:test';import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,writeFileSync,rmSync} from 'node:fs';import {join} from 'node:path';import {tmpdir} from 'node:os';
import {inspect,main} from '../bin/inspect-readonly.mjs';import {graphFixture,encodeExchange} from './helpers.mjs';
test('standalone diagnostic remains BLOCKED despite coherent synthetic chain',()=>{
 const result=inspect({exchangeText:encodeExchange(graphFixture()),pages:new Map([['index.md','# Welcome\n']])});
 assert.equal(result.independentlyVerified,false);assert(result.verdict.startsWith('BLOCKED'));assert.equal(result.lineage.observed.candidates,1);
});
test('CLI only reads existing evidence and returns blocked exit 2',()=>{
 const d=mkdtempSync(join(tmpdir(),'lane-d-r2-readonly-'));
 try{const input=join(d,'exchange.jsonl'),wiki=join(d,'wiki');mkdirSync(wiki);writeFileSync(input,encodeExchange(graphFixture()));writeFileSync(join(wiki,'index.md'),'# Generated by fixture, not HQ\n');
   const out={data:'',write(s){this.data+=s;}};assert.equal(main(['--exchange',input,'--wiki-dir',wiki],out),2);
   assert.equal(JSON.parse(out.data).readOnly,true);
 }finally{rmSync(d,{recursive:true,force:true});}
});
test('CLI missing required args fails closed before running',()=>assert.throws(()=>main(['--exchange','not-exist']),/usage:/));
