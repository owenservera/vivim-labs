/**
 * @hq:context Hand-labelled natural-language typed-IR conformance corpus for TierFlow's visual command runtime.
 * @hq:owner vivim-labs
 * @hq:task ENGINEERING-EVIDENCE-FACTORY/W3-01
 *
 * Factory 01 — Natural Language Command Factory.
 *
 * WHAT EACH CASE ASSERTS
 *   expected.outcome   the outcome TierFlow's compiler produces TODAY for the
 *                      utterance, given the Labs broker fixture in `fixture.mjs`.
 *                      This is the hard label: `independent-oracle.mjs`
 *                      re-derives it from the pinned source and the test fails
 *                      if the two disagree.
 *   expected.command   the exact typed IR (semantic id + version, target,
 *                      arguments, scope) when the outcome is `accepted`.
 *   requirement        the forward contract: what a conforming natural-language
 *                      layer must eventually produce. It is NOT enforced by the
 *                      oracle; the oracle reports every gap between the
 *                      requirement and today's behaviour as a finding.
 *
 * WHY MANY CASES EXPECT `clarification`
 * TierFlow's text surface is a CLOSED grammar: the canonical typed text
 * `/semantic.id@version key="value"`, or an exact registered `textAlias`
 * (src/visual-runtime/command/compile.ts:13-30, 69-79). There is no synonym
 * expansion, no locale awareness, no prior-state channel and no multi-intent
 * resolver in the pinned source. Every ordinary English sentence therefore
 * lands on `UNKNOWN_TEXT` -> `clarification_required`. Labelling those cases
 * `accepted` would be inventing a behaviour that does not exist, so this
 * corpus records the real behaviour and states the missing capability in
 * `requirement`.
 *
 * SCOPE IS NOT IN THE IR
 * `vivim.visual-command/1` carries no scope field
 * (src/visual-runtime/command/ir.ts:17-28). The scope recorded here is the
 * grant scope the OWNING authority demands, proven by the oracle against the
 * real owner modules. The action -> scope binding is a Labs judgement; the
 * scope vocabulary is TierFlow's.
 *
 * MATURITY: fixture / unit level only. Never device, Host, browser or
 * production evidence.
 */

